#!/usr/bin/env node
/**
 * Convert the atlas's js/map-data.js (window.INDIA_MAP: Datameet-derived
 * state/district lon-lat rings) into data/atlas/boundaries.json — plain data
 * the Paramountcy client can fetch and stroke onto its canvas. Rings stay in
 * geographic degrees; both renderers use an equirectangular projection with a
 * cos-latitude x-correction, so the client feeds them to proj.toX/toY as-is.
 *
 *   node tools/build-atlas-geo.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const src = readFileSync(join(root, 'js', 'map-data.js'), 'utf8');
const window = {};
new Function('window', src)(window);
const M = window.INDIA_MAP;

function centroid(rings) {
  let best = rings[0];
  for (const r of rings) if (r.length > best.length) best = r;
  let x = 0, y = 0, n = best.length / 2;
  for (let i = 0; i < best.length; i += 2) { x += best[i]; y += best[i + 1]; }
  return [Math.round((x / n) * 1000) / 1000, Math.round((y / n) * 1000) / 1000];
}

const states = Object.entries(M.states).map(([slug, st]) => {
  // two single-district UTs ship no separate outline: their district rings are it
  const outline = st.outline && st.outline.length ? st.outline : st.districts.flatMap((d) => d.p);
  return {
  id: 'BND.' + slug.toUpperCase().replace(/-/g, '_'),
  slug,
  name: st.name,
  c: centroid(outline),
  outline: outline,
  districts: st.districts.map((d, i) => ({
    id: 'BND.' + slug.toUpperCase().replace(/-/g, '_') + '.' + i,
    name: d.n,
    c: centroid(d.p),
    rings: d.p
  }))
  };
});

const out = {
  note: 'State and district boundary rings in lon/lat degrees, generated by tools/build-atlas-geo.mjs from js/map-data.js. Simplified community geometry for visualisation only — not an authoritative representation of national or internal boundaries.',
  source: M.attribution,
  bbox: M.bbox,
  states
};

const dir = join(root, 'data', 'atlas');
mkdirSync(dir, { recursive: true });
const path = join(dir, 'boundaries.json');
writeFileSync(path, JSON.stringify(out));
const districts = states.reduce((n, s) => n + s.districts.length, 0);
console.log(`wrote ${path}: ${states.length} states, ${districts} districts, ${(JSON.stringify(out).length / 1024).toFixed(0)} KB`);
