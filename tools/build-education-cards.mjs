#!/usr/bin/env node
/**
 * Build data/corpus/education.json — the education deck — from the atlas
 * game's authored packs (atlas-data/gita.js, atlas-data/skills.js). Each card
 * carries a crisp recitable line and points at the corpus work it teaches, so
 * the Teach lens can arm it and `decide('recite', {work, district})` does the
 * rest. Data only; regenerate after editing the atlas packs.
 *
 *   node tools/build-education-cards.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (p) => {
  const window = {};
  new Function('window', readFileSync(join(root, p), 'utf8'))(window);
  return window.INDIA_DATA;
};

const gita = load('atlas-data/gita.js').gita;
const skills = load('atlas-data/skills.js').skills;

/** Which corpus work each skill card teaches. */
const SKILL_WORK = {
  'skill-agri-1': 'WRK.KRISHIPARASHARA',
  'skill-agri-2': 'WRK.KRISHIPARASHARA',
  'skill-cattle-1': 'WRK.KRISHIPARASHARA', // plough cattle are its heart
  'skill-cattle-2': 'WRK.KRISHIPARASHARA',
  'skill-craft-1': 'WRK.ARTHASHASTRA',     // guilds and crafts oversight
  'skill-craft-2': 'WRK.ARTHASHASTRA',
  'skill-arith-1': 'WRK.ARYABHATIYA',
  'skill-arith-2': 'WRK.LILAVATI',
};

const cards = [
  ...gita.chapters.map((ch) => ({
    id: 'EDU.GITA.' + String(ch.n).padStart(2, '0'),
    work: 'WRK.GITA',
    kind: 'gita',
    title: 'Gita Ch. ' + ch.n,
    subtitle: ch.name.en,
    recite: ch.recite,
    summary: ch.summary,
    sloka: ch.sloka,
    source: 'Public-domain text; summaries after Telang (SBE Vol. 8, 1882) and Arnold (1885)'
  })),
  ...skills.cards.map((sk) => ({
    id: 'EDU.' + sk.id.toUpperCase().replace(/-/g, '.'),
    work: SKILL_WORK[sk.id],
    kind: 'skill',
    title: sk.title,
    subtitle: sk.subtitle,
    recite: sk.recite,
    summary: sk.summary,
    source: sk.source
  })),
];

const out = {
  note: 'The education deck: recitable cards over corpus works, generated by tools/build-education-cards.mjs from atlas-data/gita.js and atlas-data/skills.js.',
  cards
};
const path = join(root, 'data', 'corpus', 'education.json');
writeFileSync(path, JSON.stringify(out, null, 1));
console.log(`wrote ${path}: ${cards.length} cards`);
